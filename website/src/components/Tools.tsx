const SCAN_SPECIMENS = [
  "swiftui",
  "kubetrace",
  "python",
  "store",
  "coffee",
] as const;

function Head({ file }: { file: string }) {
  const t = TOOLS.find((item) => item.file === file) ?? TOOLS[0];
  return (
    <div className="min-w-0">
      <p className="font-pixel text-[0.6875rem] tracking-[0.06em] text-action uppercase">
        {t.file}
      </p>
      <p className="mt-3 max-w-[48ch] text-[0.9375rem] leading-relaxed text-ink-muted">
        {t.blurb}
      </p>
      <code className="mt-4 block max-w-full overflow-x-auto rounded-ctl bg-void/70 px-3.5 py-2 text-[0.75rem] leading-relaxed whitespace-pre-wrap break-words text-ink-muted">
        $ {t.command}
      </code>
    </div>
  );
}

export function Tools() {
  const [scanId, setScanId] = useState<string>("swiftui");
  const [tokenFmt, setTokenFmt] = useState<string>("css");
  const [bpLabel, setBpLabel] = useState<string>("desktop");
  const reducedMotion = useReducedMotion();

  const scanTargets = SCAN_SPECIMENS.map((id) =>
    GALLERY.find((g) => g.id === id),
  ).filter((g): g is NonNullable<typeof g> => Boolean(g));
  const activeScanItem = scanTargets.find((g) => g.id === scanId) ?? GALLERY[0];
  const scan = activeScanItem.scanBefore;

  const device = (w: number, h: number) => {
    const k = 110 / 1440;
    return {
      width: Math.round(w * k * (w > 1000 ? 1 : 1.85)),
      height: Math.round(h * k * (w > 1000 ? 1 : 1.85)),
    };
  };

  return (
    <section id="tools" aria-labelledby="tools-title" className="relative">
      <div className="mx-auto max-w-[88rem] px-4 py-16 sm:px-8 sm:py-24 lg:py-32">
        <SectionHead
          id="tools-title"
          kicker={`${TOTAL_SCRIPTS} zero-dependency scripts`}
          title={`Not just prose. ${TOTAL_SCRIPTS} tools you can execute.`}
        >
          <p>
            Every script uses Node.js built-ins only and supports{" "}
            <code className="text-ink">--help</code>. Switch targets below to
            inspect real CLI output across platforms and languages.
          </p>
        </SectionHead>

        <div className="mt-12 grid min-w-0 gap-3 sm:mt-14 lg:grid-cols-6">
          <SpotTile className="rounded-card p-5 sm:p-8 lg:col-span-4 lg:row-span-2">
            <div className="flex h-full min-w-0 flex-col gap-6">
              <Head file="slop-scan.mjs" />
              <div className="min-w-0">
                <div className="flex flex-wrap items-center justify-between gap-2">
                  <p className="font-mono text-[0.75rem] text-ink-faint">
                    real output · score{" "}
                    <span className="font-semibold text-p0 tabular">
                      {scan.score}
                    </span>
                  </p>
                  <div
                    role="group"
                    aria-label="Select scanned specimen"
                    className="inline-flex flex-wrap gap-1 rounded-tile bg-void/60 p-1 sm:rounded-full"
                  >
                    {scanTargets.map((g) => {
                      const on = g.id === activeScanItem.id;
                      return (
                        <button
                          key={g.id}
                          type="button"
                          aria-pressed={on}
                          onClick={() => setScanId(g.id)}
                          className={`relative min-h-8 rounded-full px-3 py-1 font-mono text-[0.6875rem] transition-colors motion-reduce:transition-none ${
                            on
                              ? "font-medium text-on-action"
                              : "text-ink-muted hover:text-ink"
                          }`}
                        >
                          {on ? (
                            <motion.span
                              layoutId={
                                reducedMotion ? undefined : "tool-scan-pill"
                              }
                              aria-hidden="true"
                              transition={
                                reducedMotion
                                  ? { duration: 0 }
                                  : {
                                      type: "spring",
                                      stiffness: 420,
                                      damping: 32,
                                    }
                              }
                              className="pointer-events-none absolute inset-0 rounded-full bg-action"
                            />
                          ) : null}
                          <span className="relative z-10">{g.id}</span>
                        </button>
                      );
                    })}
                  </div>
                </div>
                <AnimatePresence mode="wait" initial={false}>
                  <motion.ul
                    key={activeScanItem.id}
                    initial={reducedMotion ? false : { opacity: 0, y: 6 }}
                    animate={{ opacity: 1, y: 0 }}
                    exit={reducedMotion ? undefined : { opacity: 0, y: -6 }}
                    transition={{ duration: reducedMotion ? 0 : 0.16 }}
                    className="mt-3 grid min-w-0 gap-1.5"
                  >
                    {scan.findings.slice(0, 6).map((f, i) => (
                      <li
                        key={f.rule + i}
                        className="flex min-w-0 flex-wrap items-baseline gap-x-3 gap-y-1 rounded-ctl bg-void/50 px-3.5 py-2 font-mono text-[0.8125rem] sm:rounded-full sm:px-4"
                      >
                        <span className={`${SEV[f.severity]} w-6 shrink-0`}>
                          {f.severity}
                        </span>
                        <span className="min-w-0 break-words text-ink">
                          {f.rule}
                        </span>
                        <span className="ms-auto shrink-0 text-ink-faint tabular">
                          before.html:{f.line}
                        </span>
                      </li>
                    ))}
                  </motion.ul>
                </AnimatePresence>
              </div>
              <div className="mt-auto">
                <p className="font-mono text-[0.75rem] text-ink-faint">
                  {SCAN_RULES.length} rule IDs
                </p>
                <ul className="mt-3 flex flex-wrap gap-1.5">
                  {SCAN_RULES.map((r) => (
                    <li
                      key={r}
                      className="rounded-full border border-white/10 px-2.5 py-1 font-mono text-[0.6875rem] text-ink-muted"
                    >
                      {r}
                    </li>
                  ))}
                </ul>
              </div>
            </div>
          </SpotTile>

          <SpotTile className="rounded-card p-5 sm:p-7 lg:col-span-2">
            <Head file="shoot.mjs" />
            <div
              role="group"
              aria-label="Inspect capture breakpoint"
              className="mt-6 flex flex-wrap items-end gap-3"
            >
              {SHOOT_BREAKPOINTS.map((b) => {
                const d = device(b.w, b.h);
                const on = b.label === bpLabel;
                return (
                  <button
                    key={b.label}
                    type="button"
                    aria-pressed={on}
                    onClick={() => setBpLabel(b.label)}
                    className="group/bp flex cursor-pointer flex-col items-center gap-2"
                  >
                    <div
                      style={d}
                      className={`rounded-[10px] border-2 transition-colors motion-reduce:transition-none ${
                        on
                          ? "border-action bg-action/22 shadow-[0_0_20px_-6px_var(--color-action)]"
                          : "border-action/45 bg-action/6 group-hover/bp:border-action/80"
                      }`}
                    />
                    <span
                      className={`font-mono text-[0.6875rem] leading-tight ${
                        on ? "text-action" : "text-ink-faint"
                      }`}
                    >
                      {b.label}
                      <span className="block tabular">
                        {b.w}×{b.h}
                      </span>
                    </span>
                  </button>
                );
              })}
            </div>
          </SpotTile>

          <SpotTile className="rounded-card p-5 sm:p-7 lg:col-span-2">
            <Head file="finish-gate.mjs" />
            <ul className="mt-6 grid gap-2">
              {GATE_EXITS.map((g) => (
                <li
                  key={g.code}
                  className="flex items-center gap-3 rounded-full bg-void/50 px-4 py-2.5 font-mono text-[0.8125rem]"
                >
                  <span
                    className={`grid size-6 shrink-0 place-items-center rounded-full text-[0.75rem] tabular ${
                      g.code === 0
                        ? "bg-action font-medium text-on-action"
                        : "bg-white/10 text-ink"
                    }`}
                  >
                    {g.code}
                  </span>
                  <span className="text-ink">{g.label}</span>
                </li>
              ))}
            </ul>
          </SpotTile>

          <SpotTile className="rounded-card p-5 sm:p-8 lg:col-span-3">
            <Head file="export-tokens.mjs" />
            <div
              role="tablist"
              aria-label="Token export target format"
              className="mt-5 flex flex-wrap gap-1.5"
            >
              {TOKEN_FORMATS.map((f) => {
                const on = f === tokenFmt;
                return (
                  <button
                    key={f}
                    type="button"
                    role="tab"
                    aria-selected={on}
                    onClick={() => setTokenFmt(f)}
                    className={`relative min-h-8 rounded-full px-3 py-1 font-mono text-[0.75rem] transition-colors motion-reduce:transition-none ${
                      on
                        ? "font-medium text-on-action"
                        : "bg-action/8 text-action hover:bg-action/16"
                    }`}
                  >
                    {on ? (
                      <motion.span
                        layoutId={
                          reducedMotion ? undefined : "token-format-pill"
                        }
                        aria-hidden="true"
                        transition={
                          reducedMotion
                            ? { duration: 0 }
                            : {
                                type: "spring",
                                stiffness: 430,
                                damping: 33,
                              }
                        }
                        className="pointer-events-none absolute inset-0 rounded-full bg-action"
                      />
                    ) : null}
                    <span className="relative z-10">{f}</span>
                  </button>
                );
              })}
            </div>
            <AnimatePresence mode="wait" initial={false}>
              <motion.pre
                key={tokenFmt}
                initial={reducedMotion ? false : { opacity: 0, y: 5 }}
                animate={{ opacity: 1, y: 0 }}
                exit={reducedMotion ? undefined : { opacity: 0, y: -5 }}
                transition={{ duration: reducedMotion ? 0 : 0.15 }}
                className="mt-4 overflow-x-auto rounded-tile bg-void/65 p-4 text-[0.75rem] leading-6 text-ink-muted"
              >
                <code>
                  {(TOKEN_OUTPUTS[tokenFmt] ?? TOKEN_OUTPUTS.css).join("\n")}
                </code>
              </motion.pre>
            </AnimatePresence>
          </SpotTile>

          <SpotTile className="rounded-card p-5 sm:p-8 lg:col-span-3">
            <Head file="style-inventory.mjs" />
            <ul className="mt-6 grid grid-cols-1 gap-2 sm:grid-cols-2">
              {[
                "check-contrast.mjs (WCAG 2.2 + APCA)",
                "check-email.mjs (102 KB + Outlook)",
                "check-tui.mjs (NO_COLOR + cell width)",
                "check-pdf.mjs (PDF/UA + embedded fonts)",
              ].map((m) => (
                <li
                  key={m}
                  className="flex min-w-0 items-center gap-2.5 rounded-ctl bg-void/50 px-3.5 py-2.5 font-mono text-[0.75rem] text-ink-muted"
                >
                  <PixelIcon name="check" size={11} className="text-action" />
                  <span className="min-w-0 break-words">{m}</span>
                </li>
              ))}
            </ul>
          </SpotTile>
        </div>

        <div className="mt-14 grid min-w-0 gap-6 lg:grid-cols-12 lg:items-center">
          <div className="min-w-0 lg:col-span-4">
            <p className="font-pixel text-[0.75rem] tracking-[0.06em] text-ink-faint uppercase">
              Installed for Claude Code
            </p>
            <p className="mt-3 text-[0.9375rem] leading-relaxed text-ink-muted">
              The installer adds four slash commands next to the skills.
            </p>
          </div>
          <ul className="grid min-w-0 gap-3 sm:grid-cols-2 lg:col-span-8">
            {COMMANDS.map((c) => (
              <li
                key={c.cmd}
                className="surface flex min-w-0 flex-col items-start gap-3 rounded-tile p-4 xl:flex-row xl:items-center xl:gap-4 xl:rounded-full"
              >
                <code className="rounded-full bg-action px-4 py-2 text-[0.8125rem] font-medium whitespace-nowrap text-on-action">
                  {c.cmd}
                </code>
                <span className="text-[0.875rem] leading-snug text-ink-muted">
                  {c.does}
                </span>
              </li>
            ))}
          </ul>
        </div>
      </div>
    </section>
  );
}
